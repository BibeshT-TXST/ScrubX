"use client";

import { Database, ShieldCheck, SlidersHorizontal, Sparkles, Stethoscope, WifiOff } from "lucide-react";
import { motion } from "motion/react";
import Link from "next/link";
import { usePathname } from "next/navigation";
import { Button } from "@/components/ui/button";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuGroup,
  DropdownMenuLabel,
  DropdownMenuRadioGroup,
  DropdownMenuRadioItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import { setDisplay, useDisplay, type Density, type Theme } from "@/lib/display";
import { cn } from "@/lib/utils";

const NAV = [
  { href: "/", label: "Chat", icon: Stethoscope },
  { href: "/security", label: "Security Division", icon: ShieldCheck },
];

interface Props {
  /** Null when no model is configured: every chat will report it couldn't connect. */
  model: string | null;
  source: "demo" | "supabase";
}

export function AppHeader({ model, source }: Props) {
  const pathname = usePathname();

  return (
    <header className="flex h-14 shrink-0 items-center gap-4 border-b bg-background px-4">
      <Link href="/" className="flex items-center gap-2 rounded-md px-1 text-body font-semibold">
        <span aria-hidden className="grid size-7 place-items-center rounded-md bg-foreground text-background">
          <ShieldCheck className="size-4" />
        </span>
        ScrubX
      </Link>

      <nav aria-label="Main" className="flex h-full items-stretch gap-1">
        {NAV.map(({ href, label, icon: Icon }) => {
          const active = pathname === href;
          return (
            <Link
              key={href}
              href={href}
              aria-current={active ? "page" : undefined}
              className={cn(
                "relative flex items-center gap-2 px-3 text-data font-medium whitespace-nowrap transition-colors",
                active ? "text-foreground" : "text-muted-foreground hover:text-foreground",
              )}
            >
              <Icon className="size-4" />
              <span className="hidden sm:inline">{label}</span>
              {active && <motion.span layoutId="nav-active" className="absolute inset-x-2 -bottom-px h-0.5 rounded-full bg-foreground" />}
            </Link>
          );
        })}
      </nav>

      <div className="ml-auto flex items-center gap-2">
        <Tooltip>
          <TooltipTrigger
            render={
              <span className="hidden h-9 items-center gap-2 rounded-lg border px-3 text-meta font-medium whitespace-nowrap text-muted-foreground xl:flex" tabIndex={0} />
            }
          >
            <Database className="size-4" />
            {source === "demo" ? "Synthetic demo data" : "Supabase · read-only"}
          </TooltipTrigger>
          <TooltipContent>
            {source === "demo" ? "Every patient here is fictional." : "Patient records are read server-side; this app never writes them."}
          </TooltipContent>
        </Tooltip>

        <Tooltip>
          <TooltipTrigger
            render={
              <span
                tabIndex={0}
                className={cn(
                  "flex h-9 items-center gap-2 rounded-lg border px-3 text-meta font-medium whitespace-nowrap",
                  model ? "text-foreground" : "border-notice/30 bg-notice-surface text-notice",
                )}
              />
            }
          >
            {model ? <Sparkles className="size-4" aria-label={`AI model ${model}`} /> : <WifiOff className="size-4" aria-label="No AI model connected" />}
            <span className="hidden xl:inline">{model ? `AI model · ${model}` : "No AI model connected"}</span>
          </TooltipTrigger>
          <TooltipContent>
            {model
              ? "Answers in Chat are AI-generated by this model, after ScrubX checks and tokenizes the request."
              : "Messages are still checked by ScrubX, but every reply will say we couldn't connect."}
          </TooltipContent>
        </Tooltip>

        <DisplayMenu />
      </div>
    </header>
  );
}

function DisplayMenu() {
  const display = useDisplay();
  return (
    <DropdownMenu>
      <Tooltip>
        <TooltipTrigger render={<DropdownMenuTrigger render={<Button variant="ghost" size="icon" aria-label="Display settings" />} />}>
          <SlidersHorizontal />
        </TooltipTrigger>
        <TooltipContent>Display settings</TooltipContent>
      </Tooltip>
      <DropdownMenuContent align="end" className="w-56">
        <DropdownMenuGroup>
          <DropdownMenuLabel>Theme</DropdownMenuLabel>
          <DropdownMenuRadioGroup value={display.theme} onValueChange={(theme: Theme) => setDisplay({ theme })}>
            <DropdownMenuRadioItem value="system">Match system</DropdownMenuRadioItem>
            <DropdownMenuRadioItem value="light">Light</DropdownMenuRadioItem>
            <DropdownMenuRadioItem value="dark">Dark (night shift)</DropdownMenuRadioItem>
          </DropdownMenuRadioGroup>
        </DropdownMenuGroup>
        <DropdownMenuSeparator />
        <DropdownMenuGroup>
          <DropdownMenuLabel>Density</DropdownMenuLabel>
          <DropdownMenuRadioGroup value={display.density} onValueChange={(density: Density) => setDisplay({ density })}>
            <DropdownMenuRadioItem value="comfortable">Comfortable</DropdownMenuRadioItem>
            <DropdownMenuRadioItem value="compact">Compact</DropdownMenuRadioItem>
          </DropdownMenuRadioGroup>
        </DropdownMenuGroup>
      </DropdownMenuContent>
    </DropdownMenu>
  );
}
